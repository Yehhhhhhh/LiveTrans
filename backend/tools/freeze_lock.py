"""Write backend/requirements.lock: the exact versions installed in the current environment for
requirements.txt and everything it pulls in (dev tools such as pytest are left out).

Run it with the project's venv after upgrading and testing dependencies:

    .venv\\Scripts\\python backend\\tools\\freeze_lock.py
"""

from __future__ import annotations

import sys
from importlib import metadata
from pathlib import Path

try:
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name
except ImportError:  # pip always vendors packaging
    from pip._vendor.packaging.requirements import Requirement
    from pip._vendor.packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parent.parent
REQUIREMENTS = BACKEND / "requirements.txt"
LOCK = BACKEND / "requirements.lock"


def top_level(path: Path) -> list[Requirement]:
    reqs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            reqs.append(Requirement(line))
    return reqs


def closure(roots: list[Requirement]) -> dict[str, metadata.Distribution]:
    """Installed distributions reachable from roots, following requirements whose markers apply."""
    found: dict[str, metadata.Distribution] = {}
    # (package, extra) pairs already expanded, "" being the package itself. Each is expanded
    # once, so cycles terminate, including ones through extras (a[x] -> b[y] -> a[x]).
    seen: set[tuple[str, str]] = set()
    todo = [(r, frozenset()) for r in roots]
    while todo:
        req, parent_extras = todo.pop()
        # req comes from a package requested with parent_extras; its marker may name one of them.
        env_ok = req.marker is None or any(
            req.marker.evaluate({"extra": e}) for e in (parent_extras or {""})
        )
        if not env_ok:
            continue
        name = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            sys.exit(f"{req.name} is required but not installed; run pip install -r requirements.txt first")
        if not req.specifier.contains(dist.version, prereleases=True):
            sys.exit(f"installed {req.name} {dist.version} does not satisfy {req}")
        found[name] = dist
        new = {e for e in {"", *req.extras} if (name, e) not in seen}
        if not new:
            continue
        seen.update((name, e) for e in new)
        for sub in dist.requires or []:
            todo.append((Requirement(sub), frozenset(new)))
    return found


def main() -> None:
    dists = closure(top_level(REQUIREMENTS))
    py = f"{sys.version_info.major}.{sys.version_info.minor}"
    lines = [
        "# Exact versions LiveTrans is tested with (Windows, Python " + py + ").",
        "# install.bat installs from this file. Generated by backend/tools/freeze_lock.py",
        "# from requirements.txt; regenerate it after upgrading and testing dependencies.",
    ]
    for name in sorted(dists):
        lines.append(f"{dists[name].metadata['Name']}=={dists[name].version}")
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {LOCK} ({len(dists)} packages)")


if __name__ == "__main__":
    main()
